const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const dir = path.join(__dirname, '../app/src/main/java/com/miowser/app/browser/media');
const page = fs.readFileSync(path.join(dir, 'PageMediaScript.kt'), 'utf8');
const httpUrl = page.slice(page.indexOf('    function httpUrl('), page.indexOf('    function listen('));
const artwork = fs.readFileSync(path.join(dir, 'MediaArtworkScript.kt'), 'utf8').split('"""')[1];
let coverUrl = 'https://images.example.com/first.jpg';
let documentQueries = 0;
const bar = { isConnected: true, querySelector: () => ({ getAttribute: () => coverUrl, currentSrc: coverUrl }) };
const ctx = vm.createContext({ URL, location: { href: 'https://music.youtube.com/watch?v=one', hostname: 'music.youtube.com' },
  document: { querySelector: (selector) => { assert.equal(selector, 'ytmusic-player-bar'); documentQueries++; return bar; } } });
vm.runInContext(httpUrl + artwork, ctx);
const select = (art, poster = '') => ctx.selectMediaArtwork({ artwork: art }, { poster });
assert.equal(select([{ src: '/tiny', sizes: '48x48' }, { src: '/cover', sizes: '512x512' }]), 'https://music.youtube.com/cover');
assert.equal(select([{ src: '/wide', sizes: '1024x128' }, { src: '/square', sizes: '512x512' }]), 'https://music.youtube.com/square');
assert.equal(select([{ src: '/large', sizes: '8192x8192' }, { src: '/target', sizes: '512x512' }]), 'https://music.youtube.com/target');
assert.equal(select([{ src: '/unknown-size' }]), 'https://music.youtube.com/unknown-size');
assert.equal(documentQueries, 0, 'Valid Media Session artwork never scans the document');
assert.equal(select([{ src: 'javascript:alert(1)' }, { src: 'https://user:password@example.com/art' }, { src: '/valid' }]), 'https://music.youtube.com/valid');
assert.equal(select([]), coverUrl);
coverUrl = 'https://images.example.com/next.jpg';
assert.equal(select([]), coverUrl, 'Late track artwork replaces the previous URL');
assert.equal(documentQueries, 1, 'The connected player-bar root is reused');
ctx.location.hostname = 'example.com';
assert.equal(select([], 'https://example.com/poster.jpg'), 'https://example.com/poster.jpg');
assert.equal(select([], 'data:image/png;base64,AA'), null);
console.log('Media artwork selection: 9 scenarios passed');
